/** Get a translation string — falls back to English, then French */
export function t(lang, key) {
  if (TRANSLATIONS[lang]?.[key] !== undefined) return TRANSLATIONS[lang][key];
  if (TRANSLATIONS["en"]?.[key] !== undefined) return TRANSLATIONS["en"][key];
  return TRANSLATIONS["fr"]?.[key] ?? key;
}

/** Read language from localStorage (safe for SSR) */
export function getLang() {
  if (typeof window === "undefined") return "fr";
  const saved = localStorage.getItem("cvadapt_lang");
  return saved === "en" ? "en" : "fr";
}
